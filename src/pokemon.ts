export const GEN1_POKEMON: readonly PokemonEntry[] = GEN1_NAMES.map((name, index) => ({
  species: index + 1,
  name,
}));

const POKEMON_BY_SPECIES = new Map(GEN1_POKEMON.map((pokemon) => [pokemon.species, pokemon]));

export function pokemonName(species: number) {
  return POKEMON_BY_SPECIES.get(species)?.name ?? `#${String(species).padStart(3, "0")}`;
}

export function pokemonSpriteUrl(species: number) {
  const number = String(species).padStart(4, "0");
  return `https://raw.githubusercontent.com/PMDCollab/SpriteCollab/master/portrait/${number}/Normal.png`;
}
